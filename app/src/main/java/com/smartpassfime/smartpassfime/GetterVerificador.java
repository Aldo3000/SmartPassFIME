package com.smartpassfime.smartpassfime;
public class GetterVerificador {
    private String UsuarioVerificador;
    private String CorreoVerificador;
    public GetterVerificador(){

    }

    public String getUsuarioVerificador() {
        return UsuarioVerificador;
    }

    public void setUsuarioVerificador(String UsuarioVerificador) {
        this.UsuarioVerificador = UsuarioVerificador;
    }

    public String getCorreoVerificador() {
        return CorreoVerificador;
    }

    public void setCorreoVerificador(String CorreoVerificador) {
        this.CorreoVerificador = CorreoVerificador;
    }
}